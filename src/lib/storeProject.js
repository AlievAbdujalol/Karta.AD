const COMPONENT_CHECKOUT = [
  "import { useState } from 'react';",
  "import { createStoreOrder } from '../lib/kartaApi.js';",
  '',
  'const PHONE_RE = /^\\+?[0-9() -]{7,20}$/;',
  '',
  'export default function Checkout({ items, settings, onDone }) {',
  '  const [name, setName] = useState("");',
  '  const [phone, setPhone] = useState("");',
  '  const [address, setAddress] = useState("");',
  '  const [pickup, setPickup] = useState(false);',
  '  const [payment, setPayment] = useState("cash");',
  '  const [busy, setBusy] = useState(false);',
  '  const [message, setMessage] = useState(null);',
  '',
  '  const providers = settings.payment?.providers || ["cash"];',
  '  const canSubmit = items.length > 0 && name.trim() && PHONE_RE.test(phone)',
  '    && (pickup || address.trim()) && !busy;',
  '',
  '  async function submit(e) {',
  '    e.preventDefault();',
  '    if (!canSubmit) return;',
  '    setBusy(true);',
  '    setMessage(null);',
  '    try {',
  '      const result = await createStoreOrder({',
  '        items: items.map((it) => ({ product_id: it.product_id, quantity: it.quantity })),',
  '        customer: { name: name.trim(), phone: phone.trim() },',
  '        delivery: { type: pickup ? "pickup" : "delivery", address: pickup ? "" : address.trim() },',
  '        paymentMethod: payment,',
  '      });',
  '      setMessage({ ok: true, text: `Заказ №${String(result.order_id).slice(0, 8)} принят. Сумма: ${result.total} TJS` });',
  '      onDone();',
  '    } catch (err) {',
  '      setMessage({ ok: false, text: err.message });',
  '    } finally {',
  '      setBusy(false);',
  '    }',
  '  }',
  '',
  '  if (items.length === 0) return null;',
  '',
  '  return (',
  '    <form className="checkout" onSubmit={submit}>',
  '      <h2>Оформление заказа</h2>',
  '      <input value={name} onChange={(e) => setName(e.target.value)} placeholder="Имя" required />',
  '      <input value={phone} onChange={(e) => setPhone(e.target.value)} placeholder="+992 …" required />',
  '      <label className="row">',
  '        <input type="checkbox" checked={pickup} onChange={(e) => setPickup(e.target.checked)} />',
  '        Самовывоз',
  '      </label>',
  '      {!pickup && (',
  '        <input value={address} onChange={(e) => setAddress(e.target.value)} placeholder="Адрес доставки" required />',
  '      )}',
  '      <label>',
  '        Способ оплаты:',
  '        <select value={payment} onChange={(e) => setPayment(e.target.value)}>',
  '          {providers.includes("cash") && <option value="cash">Наличными</option>}',
  '          {providers.includes("card") && <option value="card">Картой при получении</option>}',
  '        </select>',
  '      </label>',
  '      <button className="btn" type="submit" disabled={!canSubmit}>',
  '        {busy ? "Отправка…" : "Заказать"}',
  '      </button>',
  '      {message && (',
  '        <p className={message.ok ? "ok" : "error"}>{message.text}</p>',
  '      )}',
  '    </form>',
  '  );',
  '}',
].join('\n');

const COMPONENT_DELIVERY = [
  'export default function Delivery({ settings, subtotal }) {',
  '  const d = settings.delivery || {};',
  '  if (d.enabled === false) return null;',
  '  const freeFrom = Number(d.free_from);',
  '  const free = Number.isFinite(freeFrom) && freeFrom > 0 && subtotal >= freeFrom;',
  '  const price = d.mode === "free" || free ? 0 : Number(d.price) || 0;',
  '  return (',
  '    <section className="info">',
  '      <h2>Доставка</h2>',
  '      <ul>',
  '        <li>Радиус: {Number(d.radius_km) || 10} км</li>',
  '        <li>{price > 0 ? `Стоимость: ${price} TJS` : "Бесплатно"}</li>',
  '        {Number(d.min_order) > 0 && <li>Минимальный заказ: {Number(d.min_order)} TJS</li>}',
  '        {Number.isFinite(freeFrom) && freeFrom > 0 && (',
  '          <li>Бесплатная доставка от {freeFrom} TJS</li>',
  '        )}',
  '      </ul>',
  '    </section>',
  '  );',
  '}',
].join('\n');

