function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

/**
 * API-клиент проекта: publishable anon key вшит (не секрет),
 * заказ уходит только через RPC create_store_order — сервер
 * пересчитывает цены, доставку и лимиты сам.
 */
function buildKartaApi({ supabaseUrl, anonKey, businessId }) {
  return [
    '/**',
    ' * kartaApi.js — клиент API Karta-AD для этого магазина.',
    ' * Publishable anon key вшит намеренно: он публичен по дизайну',
    ' * (как в официальном виджете Karta-AD). Секретов в файле нет.',
    ' */',
    "const SUPABASE_URL = '" + String(supabaseUrl) + "';",
    "const ANON_KEY = '" + String(anonKey) + "';",
    'const DEFAULT_BUSINESS_ID =',
    "  (import.meta.env.VITE_BUSINESS_ID || '" + String(businessId) + "')",
    '    .trim();',
    '',
    'export function businessId() {',
    '  if (!DEFAULT_BUSINESS_ID) {',
    "    throw new Error('Задайте VITE_BUSINESS_ID в .env.local');",
    '  }',
    '  return DEFAULT_BUSINESS_ID;',
    '}',
    '',
    'const BIZ_ID_RE =',
    "  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;",
    '',
    'function headers() {',
    '  return {',
    '    apikey: ANON_KEY,',
    "    Authorization: 'Bearer ' + ANON_KEY,",
    "    'Content-Type': 'application/json',",
    '  };',
    '}',
    '',
    'async function rpc(name, body) {',
    '  const res = await fetch(SUPABASE_URL + "/rest/v1/rpc/" + name, {',
    "    method: 'POST',",
    '    headers: headers(),',
    '    body: JSON.stringify(body),',
    '  });',
    '  if (!res.ok) {',
    '    const text = await res.text().catch(() => "");',
    '    let message = text;',
    '    try { message = JSON.parse(text).message || text; } catch { /* оставляем текст */ }',
    "    throw new Error(name + ': HTTP ' + res.status + ' ' + message);",
    '  }',
    '  return res.json();',
    '}',
    '',
    '/** Публичный каталог + настройки сайта (без auth). */',
    'export async function fetchStore() {',
    '  const id = businessId();',
    '  if (!BIZ_ID_RE.test(id)) throw new Error("VITE_BUSINESS_ID: ожидается UUID");',
    "  const data = await rpc('get_public_business', { p_business_id: id });",
    '  if (!data) throw new Error("Магазин не найден или не активен");',
    '  return data;',
    '}',
    '',
    '/**',
    ' * Создать заказ. Цены НЕ передаются — сервер берёт их из каталога',
    ' * (create_store_order: пересчёт цен, остатки, доставка, rate-limit).',
    ' */',
    'export async function createStoreOrder({ items, customer, delivery, paymentMethod }) {',
    '  return rpc("create_store_order", {',
    '    p_business_id: businessId(),',
    '    p_items: items,',
    '    p_customer: customer,',
    '    p_delivery: delivery,',
    '    p_payment_method: paymentMethod,',
    '  });',
    '}',
    '',
  ].join('\n');
}

function buildApp() {
  return [
    "import { useEffect, useMemo, useState } from 'react';",
    "import { fetchStore } from './lib/kartaApi.js';",
    "import Header from './components/Header.jsx';",
    "import Hero from './components/Hero.jsx';",
    "import ProductGrid from './components/ProductGrid.jsx';",
    "import Cart from './components/Cart.jsx';",
    "import Checkout from './components/Checkout.jsx';",
    "import Delivery from './components/Delivery.jsx';",
    "import Payment from './components/Payment.jsx';",
    "import Footer from './components/Footer.jsx';",
    '',
    'export default function App() {',
    '  const [store, setStore] = useState(null);',
    '  const [error, setError] = useState("");',
    '  const [cart, setCart] = useState({});',
    '  const [cartOpen, setCartOpen] = useState(false);',
    '',
    '  useEffect(() => {',
    '    fetchStore().then(setStore).catch((e) => setError(e.message));',
    '  }, []);',
    '',
    '  const add = (id) => setCart((c) => ({ ...c, [id]: (c[id] || 0) + 1 }));',
    '  const setQty = (id, qty) => setCart((c) => {',
    '    const next = { ...c };',
    '    if (qty <= 0) delete next[id];',
    '    else next[id] = Math.min(99, qty);',
    '    return next;',
    '  });',
    '',
    '  const items = useMemo(() => {',
    '    const byId = new Map((store?.products || []).map((p) => [p.id, p]));',
    '    return Object.entries(cart)',
    '      .map(([id, quantity]) => {',
    '        const product = byId.get(id);',
    '        return product ? { product_id: id, quantity, product } : null;',
    '      })',
    '      .filter(Boolean);',
    '  }, [cart, store]);',
    '',
    '  const subtotal = items.reduce(',
    '    (sum, it) => sum + Number(it.product.price) * it.quantity, 0,',
    '  );',
    '',
    '  if (error) return <main className="page"><p className="error">{error}</p></main>;',
    '  if (!store) return <main className="page"><p className="muted">Загрузка…</p></main>;',
    '',
    '  const settings = store.website_settings || {};',
    '',
    '  return (',
    '    <div className="app">',
    '      <Header name={store.name} count={items.length} onCart={() => setCartOpen(true)} />',
    '      <main className="page">',
    '        <Hero store={store} settings={settings} />',
    '        <ProductGrid products={store.products || []} cart={cart} onAdd={add} onQty={setQty} />',
    '        {settings.show_delivery !== false && <Delivery settings={settings} subtotal={subtotal} />}',
    '        {settings.show_payment !== false && <Payment settings={settings} />}',
    '        <Footer store={store} />',
    '      </main>',
    '      {cartOpen && (',
    '        <div className="overlay" role="presentation" onClick={() => setCartOpen(false)}>',
    '          <div className="sheet" onClick={(e) => e.stopPropagation()}>',
    '            <Cart items={items} subtotal={subtotal} onQty={setQty} onClose={() => setCartOpen(false)} />',
    '            <Checkout',
    '              items={items}',
    '              settings={settings}',
    '              onDone={() => { setCart({}); setCartOpen(false); }}',
    '            />',
    '          </div>',
    '        </div>',
    '      )}',
    '    </div>',
    '  );',
    '}',
  ].join('\n');
}

