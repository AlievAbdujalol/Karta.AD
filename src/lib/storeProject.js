/** Все известные маски секретов — не должны попасть ни в один файл. */
export const SECRET_PATTERNS = [
  /SERVICE_ROLE/i,
  /PAYMENT_SECRET/i,
  /OPENROUTER/i,
  /sk-or-/,
  /sb_secret_/,
  /sbp_[a-z0-9]/i,
];

/** Найти файлы с секретами: [{path, pattern}] — пусто = чисто. */
export function findSecrets(files) {
  const hits = [];
  for (const [path, content] of Object.entries(files || {})) {
    if (typeof content !== 'string') continue;
    for (const re of SECRET_PATTERNS) {
      if (re.test(content)) hits.push({ path, pattern: String(re) });
    }
  }
  return hits;
}
