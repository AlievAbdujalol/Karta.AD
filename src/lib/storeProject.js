/**
 * storeProject.js — генератор полного React-проекта магазина для ZIP-экспорта
 * (спецификация §9). Возвращает плоское дерево { 'path': 'content' }.
 *
 * Безопасность: в проект НЕ попадают секреты (SERVICE_ROLE, PAYMENT_SECRET,
 * OPENROUTER, sb_secret_) — только publishable anon key (публичен по дизайну,
 * так же встраивается в widget.js) и ссылка на app origin.
 * Проверяется тестом storeProject.test.js.
 *
 * Данные проект читает сам через get_public_business, заказ валидируется
 * сервером через RPC create_store_order — frontend-цены не считаются авторитетными.
 */

const slugify = (s) => String(s || 'store')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '')
  .slice(0, 40) || 'store';

/** Дерево файлов проекта. */
